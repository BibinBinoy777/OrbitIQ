def test_archive_detects_corrupted_response(database, record):
    sid = ingest(database, 5, transport=transport_for(json.dumps([record]).encode()))
    with closing(sqlite3.connect(database)) as db:
        # Simulate out-of-band corruption; normal application updates are forbidden.
        db.execute("DROP TRIGGER snapshots_no_update")
        db.execute("UPDATE snapshots SET raw_response=? WHERE id=?", (b"changed", sid))
        db.commit()
    from orbitiq.storage import StorageError

    with pytest.raises(StorageError, match="checksum mismatch"):
        verify_archive(database)


