def test_celestrak_omitted_invariants_are_explicit(record):
    for key in ("CENTER_NAME", "REF_FRAME", "TIME_SYSTEM", "MEAN_ELEMENT_THEORY"):
        record.pop(key)
    _, elements = parse_response(json.dumps([record]).encode(), 5)
    assert (elements.center, elements.frame, elements.time_system, elements.theory) == (
        "EARTH",
        "TEME",
        "UTC",
        "SGP4",
    )
    assert elements.epoch.utcoffset() == timedelta(0)


def transport_for(body, status=200, content_type="application/json"):
    def handler(request):
        assert request.url.host == "celestrak.org"
        assert dict(request.url.params) == {"CATNR": "5", "FORMAT": "JSON"}
        return httpx.Response(
            status,
            stream=httpx.ByteStream(body),
            headers={"content-type": content_type},
        )

    return httpx.MockTransport(handler)


def test_ingestion_persists_exact_bytes_and_history(database, record):
    raw = ("  " + json.dumps([record]) + "\n").encode()
    first = ingest(database, 5, transport=transport_for(raw))
    record["ELEMENT_SET_NO"] += 1
    second = ingest(database, 5, transport=transport_for(json.dumps([record]).encode()))
    assert second > first
    original = get_snapshot(database, first)
    assert original["raw_response"] == raw
    assert original["normalized_record"]["REF_FRAME"] == "TEME"
    assert original["element_units"]["MEAN_MOTION"] == "rev/day"
    assert original["response_sha256"] == hashlib.sha256(raw).hexdigest()
    assert original["source_url"].endswith("CATNR=5&FORMAT=JSON")
    assert datetime.fromisoformat(original["retrieved_at"]).tzinfo is not None
    assert original["validation_status"] == "structural_and_epoch_propagation_passed"
    assert [r["id"] for r in list_snapshots(database, 5)] == [second, first]
    assert list_snapshots(database, 5)[0]["freshness"] == "stale"
    assert [r["id"] for r in list_snapshots(database, 5, before_id=second)] == [first]
    with closing(sqlite3.connect(database)) as db:
        for query in [
            "UPDATE snapshots SET object_name='changed'",
            "DELETE FROM snapshots",
        ]:
            with pytest.raises(sqlite3.IntegrityError, match="immutable"):
                db.execute(query)
    assert verify_archive(database) == 2


