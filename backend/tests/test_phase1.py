def test_engine_rejects_sgp4_error_and_nonfinite_output():
    class FailedSatellite:
        def sgp4(self, jd, fraction):
            return 6, (0, 0, 0), (0, 0, 0)

    with pytest.raises(PropagationError, match="SGP4 error 6"):
        propagate_satellite(FailedSatellite(), datetime.now(UTC))

    class NonfiniteSatellite:
        def sgp4(self, jd, fraction):
            return 0, (float("nan"), 0, 0), (0, 0, 0)

    with pytest.raises(PropagationError, match="non-finite"):
        propagate_satellite(NonfiniteSatellite(), datetime.now(UTC))


