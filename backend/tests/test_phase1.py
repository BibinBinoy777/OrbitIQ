def test_propagation_requires_timezone_and_bounds_epoch(record):
    elements = Elements.model_validate(record)
    with pytest.raises(PropagationError, match="timezone"):
        propagate(elements, datetime(2000, 6, 27))
    with pytest.raises(PropagationError, match="7-day"):
        propagate(elements, elements.epoch + timedelta(days=8))
    result = propagate(elements, elements.epoch + timedelta(days=2))
    assert "24 hours" in result["warnings"][-1]
    assert result["gravity_model"] == "WGS72"


def test_migrate_v1_preserves_data_and_creates_restorable_backup(tmp_path):
    path, backup, restored = [
        tmp_path / f"{n}.sqlite3" for n in ("old", "backup", "restored")
    ]
    with closing(sqlite3.connect(path)) as db:
        db.executescript(INITIAL_MIGRATION.read_text())
        db.execute("CREATE TABLE user_data (value TEXT)")
        db.execute("INSERT INTO user_data VALUES ('preserve me')")
        db.commit()
    assert migrate(path, backup)
    with closing(sqlite3.connect(path)) as db:
        assert schema_version(db) == 2
        assert db.execute("SELECT value FROM user_data").fetchone() == ("preserve me",)
    with closing(sqlite3.connect(backup)) as db:
        assert schema_version(db) == 1
    copy_database(backup, restored)
    with closing(sqlite3.connect(restored)) as db:
        assert db.execute("SELECT value FROM user_data").fetchone() == ("preserve me",)
    assert not migrate(path, backup)  # repeat is a no-op, not a second backup overwrite


def test_migration_refuses_existing_backup_and_rolls_back_failure(
    tmp_path, monkeypatch
):
    path, backup = tmp_path / "old.sqlite3", tmp_path / "backup.sqlite3"
    with closing(sqlite3.connect(path)) as db:
        db.executescript(INITIAL_MIGRATION.read_text())
    backup.write_bytes(b"preserve existing backup")
    with pytest.raises(FileExistsError):
        migrate(path, backup)
    assert backup.read_bytes() == b"preserve existing backup"
    broken_sql = tmp_path / "broken.sql"
    broken_sql.write_text("CREATE TABLE partial (id INTEGER);\nINVALID SQL;\n")
    monkeypatch.setattr("orbitiq.database.SNAPSHOT_MIGRATION", broken_sql)
    with pytest.raises(sqlite3.Error):
        migrate(path, tmp_path / "safe-backup.sqlite3")
    with closing(sqlite3.connect(path)) as db:
        assert schema_version(db) == 1
        assert (
            db.execute("SELECT name FROM sqlite_master WHERE name='partial'").fetchone()
            is None
        )


def test_snapshot_backup_restore_verifies_content(database, record, tmp_path):
    snapshot_id = ingest(
        database, 5, transport=transport_for(json.dumps([record]).encode())
    )
    backup, restored = tmp_path / "backup.sqlite3", tmp_path / "restored.sqlite3"
    copy_database(database, backup)
