@pytest.mark.parametrize("fixture,case", REFERENCE_CASES)
@pytest.mark.parametrize("input_format", ["tle", "omm"])
def test_vallado_reference_vectors(fixture, case, input_format):
    tle_satellite = Satrec.twoline2rv(*fixture["tle"])
    at = sat_epoch_datetime(tle_satellite) + timedelta(minutes=case["minutes"])
    if input_format == "tle":
        result = propagate_satellite(tle_satellite, at)
    else:
        elements = Elements.model_validate(fixture["omm"])
        result = propagate(elements, at)
        assert result["frame"] == "TEME"
        assert result["kind"] == "calculated"
    # Published outputs, not values generated by the engine under test.
    # 1 cm / 0.01 mm/s accommodates printed precision and datetime rounding.
    assert result["position_km"] == pytest.approx(case["position_km"], abs=1e-5, rel=0)
    assert result["velocity_km_s"] == pytest.approx(
        case["velocity_km_s"], abs=1e-8, rel=0
    )


